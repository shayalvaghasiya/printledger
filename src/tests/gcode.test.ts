import { describe, it, expect } from 'vitest';
import {
  parseDuration,
  parseSeconds,
  parseGcode,
  parse3mfMetadata,
} from '../core/gcode';

describe('parseDuration', () => {
  it('parses "1h 23m 45s"', () => {
    expect(parseDuration('1h 23m 45s')).toBe(5025);
  });
  it('parses "3h 34m 8s"', () => {
    expect(parseDuration('3h 34m 8s')).toBe(3 * 3600 + 34 * 60 + 8);
  });
  it('parses "45s" and "17m 30s"', () => {
    expect(parseDuration('45s')).toBe(45);
    expect(parseDuration('17m 30s')).toBe(1050);
  });
  it('parses "2d 5h"', () => {
    expect(parseDuration('2d 5h')).toBe(2 * 86400 + 5 * 3600);
  });
  it('handles decimal seconds', () => {
    expect(parseDuration('1h 2m 3.5s')).toBeCloseTo(3600 + 120 + 3.5, 6);
  });
  it('rejects garbage', () => {
    expect(parseDuration('filament')).toBeNull();
    expect(parseDuration('')).toBeNull();
  });
});

describe('parseSeconds', () => {
  it('plain integer seconds', () => {
    expect(parseSeconds('12840')).toBe(12840);
  });
  it('seconds with s suffix', () => {
    expect(parseSeconds('12840s')).toBe(12840);
  });
  it('"1.5h"', () => {
    expect(parseSeconds('1.5h')).toBe(5400);
  });
});

describe('parseGcode', () => {
  it('PrusaSlicer header', () => {
    const text = [
      '; generated by PrusaSlicer 2.6.0 on 2024-01-01',
      '; estimated printing time (normal mode) = 3h 34m 8s',
      '; estimated printing time (silent mode) = 4h 1m 12s',
      '; filament used [mm] = 2922.3',
      '; filament used [cm3] = 7.0',
      '; filament used [g] = 8.7',
      '',
      'G28 X Y',
      'G1 X10 Y10 Z0.2 F3000',
    ].join('\n');
    const r = parseGcode(text);
    expect(r.timeSeconds).toBe(3 * 3600 + 34 * 60 + 8);
    expect(r.grams).toBe(8.7);
    expect(r.meters).toBeCloseTo(2.9223, 4);
    expect(r.warnings).toHaveLength(0);
  });

  it('Cura header with length + weight', () => {
    const text = [
      '; -- Cura Profile --',
      ';TIME:7200',
      ';Filament used: 8.7m / 29.2g',
      ';Filament length: 8.7m',
      'G28',
    ].join('\n');
    const r = parseGcode(text);
    expect(r.timeSeconds).toBe(7200);
    expect(r.meters).toBeCloseTo(8.7, 6);
    expect(r.grams).toBe(29.2);
  });

  it('Simplify3D header', () => {
    const text = [
      'G90',
      ';   Print Time:      = 3h 34m 0s',
      ';   Filament:        = 2922.3 mm (2.0 cm3)',
    ].join('\n');
    const r = parseGcode(text);
    expect(r.timeSeconds).toBe(3 * 3600 + 34 * 60);
    expect(r.meters).toBeCloseTo(2.9223, 4);
  });

  it('old Cura TIME seconds', () => {
    const r = parseGcode(';TIME:12840\nG1 X0 Y0');
    expect(r.timeSeconds).toBe(12840);
  });

  it('plain Prusa TIME line', () => {
    const r = parseGcode('; TIME:12345');
    expect(r.timeSeconds).toBe(12345);
  });

  it('file with no metadata reports warnings', () => {
    const r = parseGcode('G28\nG1 X10 F3000\nM104 S210');
    expect(r.timeSeconds).toBeNull();
    expect(r.grams).toBeNull();
    expect(r.warnings.length).toBeGreaterThan(0);
  });

  it('case-insensitive', () => {
    const r = parseGcode(';TIME:100\n;Filament Used: 5m / 12g');
    expect(r.timeSeconds).toBe(100);
    expect(r.grams).toBe(12);
    expect(r.meters).toBe(5);
  });
});

describe('parse3mfMetadata', () => {
  const curaXml = `<?xml version="1.0" encoding="UTF-8"?>
<model unit="millimeter" xml:lang="en-US" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">
  <metadata name="Application">cura</metadata>
  <metadata name="cura:print_time" preserve="1">7234</metadata>
  <metadata name="cura:material_weight" preserve="1">6.8</metadata>
  <resources>
    <object id="1" type="model">
      <mesh><vertices><vertex><xyz>0 0 0</xyz></vertex></vertices></mesh>
    </object>
  </resources>
</model>`;

  it('extracts print time and material weight', () => {
    const r = parse3mfMetadata(curaXml);
    expect(r.timeSeconds).toBe(7234);
    expect(r.grams).toBe(6.8);
  });

  it('missing fields warn', () => {
    const r = parse3mfMetadata('<model></model>');
    expect(r.timeSeconds).toBeNull();
    expect(r.warnings.length).toBeGreaterThan(0);
  });

  it('Prusa-style names', () => {
    const xml = `<metadata name="Slic3r_PE:print.time" preserve="1">1234</metadata>
<metadata name="Slic3r_PE:filament_used" preserve="1">5.2</metadata>`;
    const r = parse3mfMetadata(xml);
    expect(r.timeSeconds).toBe(1234);
    expect(r.grams).toBe(5.2);
  });
});